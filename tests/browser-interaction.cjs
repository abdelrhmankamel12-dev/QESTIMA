// Run separately on a machine with Playwright Chromium installed.
// Uses an isolated browser context and test-only demo data, not user profiles.
const { chromium } = require("playwright")
const { createServer } = require("node:http")
const fs = require("node:fs")
const path = require("node:path")
const assert = require("node:assert/strict")
const C = require("../app/core.js")
const Intake = require("../app/tender-intake.js")
async function main() {
  const root = path.resolve(__dirname, "../app")
  const server = createServer((req, res) => {
    const file = path.resolve(root, "." + (req.url === "/" ? "/index.html" : req.url.split("?")[0]))
    if (!file.startsWith(root + path.sep)) { res.writeHead(403).end(); return }
    const type = { ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml" }[path.extname(file)] || "application/octet-stream"
    try { res.setHeader("Content-Type", type); res.end(fs.readFileSync(file)) } catch { res.writeHead(404).end() }
  })
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve))
  let browser
  try {
    browser = await chromium.launch({ headless: true })
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
    const errors = []
    page.on("pageerror", (error) => errors.push(error.message))
    const fixture = C.seedState()
    const project = fixture.projects.find(p => p.id === fixture.activeProjectId) || fixture.projects[0]
    project.tenderIntake = Intake.stage(project, [{id: 'browser-contract', name: 'Contract-review.pdf', hash: 'browser-fixture-contract', fileType: 'PDF'}], 'fixture', new Date().toISOString()).queue
    await page.addInitScript((value) => !localStorage.getItem("qestima-v6") && localStorage.setItem("qestima-v6", JSON.stringify(value)), fixture)
    await page.goto(`http://127.0.0.1:${server.address().port}/`)
    await page.locator('#workspace button[data-action="new-project"]').first().waitFor({ state: 'visible' })
    assert.equal(await page.locator('#login-screen:visible').count(), 0)
    await page.locator('#main-nav button[data-view="boq"]').click()
    const editor = page.locator('input[data-boq-id][data-field="description"]').first()
    await editor.fill('')
    await editor.click()
    await editor.pressSequentially("Tender input stays focused")
    assert.equal(await editor.inputValue(), "Tender input stays focused")
    await page.locator('#main-nav button[data-view="projects"]').click()
    await page.locator("#project-search").fill("no-project-matches-this")
    assert.equal(await page.locator(".project-open:visible").count(), 0)
    await page.locator("#project-search").fill("")
    await page.locator('#workspace button[data-action="new-project"]').first().click()
    await page.locator("#project-form").waitFor({ state: "visible" })
    await page.locator('#modal-root button[data-action="close-modal"]').first().click()
    await page.locator('#main-nav button[data-view="reports"]').click()
    await page.locator('[data-report-tab="pricedBoq"]').click()
    assert.equal(await page.locator('[data-report-tab="pricedBoq"]').getAttribute("class"), "active")
    await page.locator('#ribbon-tab-tender-ai').click()
    await page.locator('#ribbon-panel-tender-ai [data-command-id="tender-intake"]').click()
    await page.locator('#workspace [data-action="intake-review"][data-id="intake-browser-contract"]').click()
    const review = page.locator('#intake-review-form')
    await review.locator('[name="documentNumber"]').fill('BROWSER-CONTRACT-001')
    await review.locator('[name="revision"]').fill('0')
    await review.locator('button[type="submit"]').click()
    await review.waitFor({state:'detached'})
    assert.equal(await page.locator('[data-action="intake-review"][data-id="intake-browser-contract"]').count(), 0)
    assert.match(await page.locator('#workspace').innerText(), /معتمد/)
    fs.mkdirSync(path.resolve(__dirname, "../artifacts"), { recursive: true })
    await page.screenshot({ path: path.resolve(__dirname, "../artifacts/tender-intake-actual.png"), fullPage: true })
    await page.locator('#main-nav button[data-view="boq"]').click()
    fs.mkdirSync(path.resolve(__dirname, "../artifacts"), { recursive: true })
    const tree = page.locator('#navigator-tree')
    assert.match(await page.locator('#navigator-title').innerText(), /أقسام وبنود/)
    await page.locator('#navigator-search').fill('Tender input stays focused')
    assert.equal(await tree.locator('[data-action="navigator-item"]').count(), 1)
    await tree.locator('[data-action="navigator-item"]').click()
    assert.equal(await page.locator('input[data-boq-id][data-field="description"]:focus').inputValue(), 'Tender input stays focused')
    await page.locator('#navigator-search').fill('')
    const splitter = page.locator('#navigator-resize')
    await splitter.focus(); await splitter.press('End')
    assert.equal(await splitter.getAttribute('aria-valuenow'), '380')
    await splitter.press('Home'); await splitter.press('ArrowRight')
    assert.equal(await splitter.getAttribute('aria-valuenow'), '200')
    const bounds = await splitter.boundingBox()
    await page.mouse.move(bounds.x + 3, bounds.y + 100); await page.mouse.down()
    await page.mouse.move(bounds.x + 53, bounds.y + 100); await page.mouse.up()
    assert.equal(await splitter.getAttribute('aria-valuenow'), '250')
    await page.locator('[data-action="toggle-navigator"]').click()
    assert.equal(await page.locator('.sidebar').isVisible(), false)
    await page.locator('[data-action="toggle-navigator"]').click()
    await page.keyboard.press('Control+s')
    await page.reload()
    await page.locator('#main-nav button[data-view="boq"]').click()
    assert.equal(await splitter.getAttribute('aria-valuenow'), '250')
    assert.equal(await page.locator('.sidebar').evaluate(el => getComputedStyle(el).backgroundImage), 'none')
    await page.setViewportSize({width:1366,height:768})
    const sidebar = await page.locator('.sidebar').boundingBox(), work = await page.locator('#workspace').boundingBox()
    assert.ok(sidebar.x < work.x && work.width > 1000)
    await page.screenshot({ path: path.resolve(__dirname, "../artifacts/workbench-actual.png"), fullPage: true })
    assert.deepEqual(errors, [])
    console.log("PASS: login, ordinary typing, filtering, internal button routing, report tabs, tender review approval, contextual tree, keyboard and pointer resize, persisted layout; screenshots saved.")
  } finally { if (browser) await browser.close(); await new Promise((resolve) => server.close(resolve)) }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
